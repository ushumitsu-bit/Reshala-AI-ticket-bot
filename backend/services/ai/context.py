def _tokens(query: str) -> list:
    words = re.findall(r"[a-zA-Zа-яА-ЯёЁ0-9]{3,}", (query or "").lower())
    return [w for w in words if w not in STOPWORDS][:12]


def _frag(tok: str) -> str:
    # префиксный матч под русскую морфологию: "настро" ловит "Настройка"/"настроить"
    return re.escape(tok[:5]) if len(tok) >= 6 else re.escape(tok)


def _render_articles(articles: list) -> str:
    parts = []
    total = 0
    for a in articles:
        category = a.get("category", "general")
        title = a.get("title", "")
        content = (a.get("content", "") or "")[:1500]
        if not (title and content):
            continue
        block = f"[{category}] {title}: {content}"
        if total + len(block) > 6000:
            break
        parts.append(block)
        total += len(block)
    return "\n---\n".join(parts)


def build_knowledge_context(db, query: str, limit: int = 4) -> str:
    """
    Ищет релевантные статьи БЗ по запросу с префиксным матчем, синонимами и
    скорингом. Если точных совпадений нет — отдаёт базовые статьи для AI.
    """
    if db is None:
        return ""

    try:
        toks = _tokens(query)
        expanded = set(toks) | {SYNONYMS[t] for t in toks if t in SYNONYMS}
        frags = [_frag(t) for t in expanded]

        articles = []
        if frags:
            regex = "|".join(frags)
            rx = {"$regex": regex, "$options": "i"}
            cands = list(db.knowledge_base.find({
                "$or": [
                    {"title": rx}, {"content": rx},
                    {"category": rx}, {"keywords": rx},
                ]
            }).limit(30))

            compiled = [re.compile(f, re.IGNORECASE) for f in frags]
            scored = []
            for a in cands:
                title = (a.get("title") or "")
                cat = (a.get("category") or "")
                kw = str(a.get("keywords") or "")
                content = (a.get("content") or "")
                score = 0
                for c in compiled:
                    if c.search(title):
                        score += 3
                    elif c.search(kw):
                        score += 2
                    elif c.search(cat):
                        score += 2
                    elif c.search(content):
                        score += 1
                if score:
                    scored.append((score, a))
            scored.sort(key=lambda x: x[0], reverse=True)
            articles = [a for _, a in scored[:limit]]

        if not articles:
            articles = list(db.knowledge_base.find(
                {"category": {"$regex": "AI-бот|диагностик|Инструкция для AI", "$options": "i"}}
            ).limit(2))

        return _render_articles(articles)
    except Exception as e:
        logger.warning(f"build_knowledge_context error: {e}")
        return ""
